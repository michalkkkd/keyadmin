"""
Generates the Host Key (ECDSA P-256). The dongle opens a secure session only for a host that signs the
handshake with it, so only Compass and keyadmin can talk to it.

    keyadmin/keys/host_key.pem                          private key, factory copy (used by keyadmin)
    KeyFirmware/src/core/crypto/host_auth_pubkey.h      public key, compiled into the firmware
    compass/app/level_x/xrouter.py  XRouter._HOST_KEY   private key, built into Compass

Usage:
    python generate_host_key.py              # create key (refuses to overwrite) + header + Compass field
    python generate_host_key.py --sync-only  # rewrite header + Compass field from the existing key
"""
import argparse
import hashlib
import os
import re
import sys

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.dirname(os.path.dirname(SCRIPT_DIR))
if REPO_ROOT not in sys.path:
    sys.path.insert(0, REPO_ROOT)

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import ec

from keyadmin.admin_factory import host_key_path
from keyadmin.core.constants import CHAR_ENCODING_UTF8

HEADER_PATH = os.path.normpath(os.path.join(REPO_ROOT, "..", "KeyFirmware", "src", "core", "crypto", "host_auth_pubkey.h"))
XROUTER_PATH = os.path.normpath(os.path.join(REPO_ROOT, "..", "compass", "app", "level_x", "xrouter.py"))
XROUTER_FIELD = re.compile(r'^(    _HOST_KEY = bytes\.fromhex\(")[0-9A-Fa-f]*("\))$', re.M)

HEADER_TEMPLATE = """#ifndef HOST_AUTH_PUBKEY_H
#define HOST_AUTH_PUBKEY_H

// =============================================================================
// Host Key, public half (P-256, 0x04 || X || Y): the dongle opens a session only for a handshake
// signed with the matching private key (Compass XRouter._HOST_KEY, keyadmin keys/host_key.pem).
// GENERATED by KeySec/keyadmin/scripts/generate_host_key.py - DO NOT EDIT.
// Fingerprint (SHA-256 of the point, first 16 hex): {fingerprint}
// =============================================================================

#include <stdint.h>

static const uint8_t host_auth_pubkey[65] = {{
{body}
}};

#endif // HOST_AUTH_PUBKEY_H
"""


def render_header(point: bytes) -> str:
    rows = [point[i:i + 13] for i in range(0, len(point), 13)]
    body = ",\n".join("    " + ", ".join(f"0x{b:02X}" for b in row) for row in rows)
    return HEADER_TEMPLATE.format(fingerprint=hashlib.sha256(point).hexdigest().upper()[:16], body=body)


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate the Host Key, firmware header and Compass field")
    parser.add_argument("--sync-only", action="store_true", help="rewrite header and Compass field from the existing key")
    args = parser.parse_args()

    key_path = host_key_path()
    try:
        if args.sync_only:
            with open(key_path, "rb") as f:
                key = serialization.load_pem_private_key(f.read(), password=None)
        else:
            if os.path.exists(key_path):
                raise RuntimeError(f"{key_path} already exists. Shipped Compass builds use it; use --sync-only.")
            key = ec.generate_private_key(ec.SECP256R1())
            with open(key_path, "wb") as f:
                f.write(key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8,
                                          serialization.NoEncryption()))
            print(f"[+] Host Key created: {key_path}")

        point = key.public_key().public_bytes(serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint)
        with open(HEADER_PATH, "w", encoding=CHAR_ENCODING_UTF8) as f:
            f.write(render_header(point))
        print(f"[+] Header written: {HEADER_PATH} (fingerprint {hashlib.sha256(point).hexdigest().upper()[:16]})")

        with open(XROUTER_PATH, encoding=CHAR_ENCODING_UTF8) as f:
            source = f.read()
        scalar = key.private_numbers().private_value.to_bytes(32, "big").hex().upper()
        source, count = XROUTER_FIELD.subn(lambda m: m.group(1) + scalar + m.group(2), source)
        if count != 1:
            raise RuntimeError(f"XRouter._HOST_KEY line not found exactly once in {XROUTER_PATH}")
        with open(XROUTER_PATH, "w", encoding=CHAR_ENCODING_UTF8, newline="") as f:
            f.write(source)
        print(f"[+] Compass field updated: {XROUTER_PATH} (XRouter._HOST_KEY)")
        print("[!] Rebuild the firmware (compile.bat) and Compass; both must carry the same key.")
        return 0
    except Exception as e:
        print(f"[-] {e}")
        return 1


if __name__ == "__main__":
    sys.exit(main())
