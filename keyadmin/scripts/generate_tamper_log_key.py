"""
Generates the Tamper Log Key (AES-128) and writes it into KeyFirmware/src/core/tamper_log_key.h.

The firmware encrypts every tamper log entry in the User Data page with this key, so a wiped dongle
(debug port open after the device erase) shows only ciphertext. The key file is read by
tamper_log_decoder.py; the firmware copy is erased together with the rest of main flash by the wipe.

Usage:
    python generate_tamper_log_key.py                # create key (refuses to overwrite) + header
    python generate_tamper_log_key.py --header-only  # regenerate header from the existing key
"""
import argparse
import hashlib
import os
import sys

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.dirname(os.path.dirname(SCRIPT_DIR))
if REPO_ROOT not in sys.path:
    sys.path.insert(0, REPO_ROOT)

from keyadmin.secure_debug.tamper_log_decoder import LOG_KEY_SIZE, default_key_path, load_key
from keyadmin.core.constants import TLOG_FIRMWARE_HEADER_RELPATH, CHAR_ENCODING_UTF8

HEADER_TEMPLATE = """#ifndef TAMPER_LOG_KEY_H
#define TAMPER_LOG_KEY_H

// =============================================================================
// Tamper Log Key (AES-128): encrypts the tamper log entries in the User Data page
// GENERATED by KeySec/keyadmin/scripts/generate_tamper_log_key.py - DO NOT EDIT.
// Fingerprint (SHA-256 of key, first 16 hex): {fingerprint}
// =============================================================================

#include <stdint.h>

static const uint8_t tamper_log_key[16] = {{
{body}
}};

#endif // TAMPER_LOG_KEY_H
"""


def render_header(key: bytes) -> str:
    rows = [key[i:i + 8] for i in range(0, len(key), 8)]
    body = ",\n".join("    " + ", ".join(f"0x{b:02X}" for b in row) for row in rows)
    return HEADER_TEMPLATE.format(fingerprint=hashlib.sha256(key).hexdigest().upper()[:16], body=body)


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate the Tamper Log Key and firmware header")
    parser.add_argument("--header-only", action="store_true", help="only regenerate the firmware header")
    args = parser.parse_args()

    key_path = default_key_path()
    try:
        if args.header_only:
            key = load_key(key_path)
        else:
            if os.path.exists(key_path):
                raise RuntimeError(f"{key_path} already exists. Dongles in the field use it; use --header-only.")
            key = os.urandom(LOG_KEY_SIZE)
            with open(key_path, "wb") as f:
                f.write(key)
            print(f"[+] Tamper Log Key created: {key_path} (keep it: without it the logs cannot be decrypted)")

        header_path = os.path.normpath(os.path.join(REPO_ROOT, *TLOG_FIRMWARE_HEADER_RELPATH))
        with open(header_path, "w", encoding=CHAR_ENCODING_UTF8) as f:
            f.write(render_header(key))
        print(f"[+] Header written: {header_path} (fingerprint {hashlib.sha256(key).hexdigest().upper()[:16]})")
        return 0
    except Exception as e:
        print(f"[-] {e}")
        return 1


if __name__ == "__main__":
    sys.exit(main())
