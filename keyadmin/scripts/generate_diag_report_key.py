"""
Generates the Diag Report Key (ECDH P-256). keycomm.diag (Compass.exe --diag) encrypts the whole diagnostic
report to its public half, so only KeySec admin can read what a customer sends.

    keyadmin/keys/diag_report_key.pem            private key (decipher, keyadmin only)
    keycomm/diag/diag_report_pubkey.py           public key, built into keycomm / Compass

Usage:
    python generate_diag_report_key.py              # create key (refuses to overwrite) + keycomm module
    python generate_diag_report_key.py --sync-only  # rewrite the keycomm module from the existing key
"""
import argparse
import hashlib
import os
import sys

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.dirname(os.path.dirname(SCRIPT_DIR))
if REPO_ROOT not in sys.path:
    sys.path.insert(0, REPO_ROOT)

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import ec

from keyadmin.core.constants import CHAR_ENCODING_UTF8, SDL_KEYS_DIRNAME, DIAG_REPORT_KEY_FILENAME

# Paths built here: the decoder imports keycomm.diag, which needs the module this script writes
KEY_PATH = os.path.join(REPO_ROOT, "keyadmin", SDL_KEYS_DIRNAME, DIAG_REPORT_KEY_FILENAME)
PUBKEY_MODULE_PATH = os.path.join(REPO_ROOT, "keycomm", "diag", "diag_report_pubkey.py")

MODULE_TEMPLATE = '''"""
Diag Report Key, public half (P-256, 0x04 || X || Y): keycomm.diag encrypts every diagnostic report to it.
The private half stays in KeySec (keyadmin/keys/diag_report_key.pem).
GENERATED by KeySec/keyadmin/scripts/generate_diag_report_key.py - DO NOT EDIT.
Fingerprint (SHA-256 of the point, first 16 hex): {fingerprint}
"""

DIAG_REPORT_PUBKEY = bytes.fromhex("{point_hex}")
'''


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate the Diag Report Key and the keycomm public key module")
    parser.add_argument("--sync-only", action="store_true", help="rewrite the keycomm module from the existing key")
    args = parser.parse_args()

    key_path = KEY_PATH
    try:
        if args.sync_only:
            with open(key_path, "rb") as f:
                key = serialization.load_pem_private_key(f.read(), password=None)
        else:
            if os.path.exists(key_path):
                raise RuntimeError(f"{key_path} already exists. Shipped Compass builds use it; use --sync-only.")
            key = ec.generate_private_key(ec.SECP256R1())
            with open(key_path, "wb") as f:
                f.write(key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8,
                                          serialization.NoEncryption()))
            print(f"[+] Diag Report Key created: {key_path}")

        point = key.public_key().public_bytes(serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint)
        with open(PUBKEY_MODULE_PATH, "w", encoding=CHAR_ENCODING_UTF8) as f:
            f.write(MODULE_TEMPLATE.format(fingerprint=hashlib.sha256(point).hexdigest().upper()[:16],
                                           point_hex=point.hex().upper()))
        print(f"[+] Public key written: {PUBKEY_MODULE_PATH}")
        return 0
    except Exception as e:
        print(f"[-] {e}")
        return 1


if __name__ == "__main__":
    sys.exit(main())
