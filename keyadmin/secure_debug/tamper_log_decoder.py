"""
Decoder for the tamper event log kept in the dongle's User Data page (0x0FE00000, 1 KB).

The layout mirrors KeyFirmware/src/core/tamper_manager.h (the firmware has a _Static_assert on the entry size):
    64 slots x 16 B, one AES-128-ECB block each, encrypted with the Tamper Log Key
    (keyadmin/keys/tamper_log_key.bin, generated by generate_tamper_log_key.py). A blank slot is all 0xFF.
    Two block kinds, told apart by the 'type' byte:
      - normal event: magic, type, count, flags, RTC(UNIX), 24-bit uptime, centiseconds, temperature, CRC-16
      - usage dump (type 0xF1): magic, type, 6 x uint16 algorithm usage counters, CRC-16
    When the page is full the firmware coalesces the oldest events of the most frequent type into one entry
    (flag COALESCED, counts summed), so rarer types keep their own rows.
The page is not touched by a device erase, a mass erase or flashing, so it is readable after the tamper wipe.
"""
import binascii
import datetime
import os
import struct
import subprocess
import sys
from dataclasses import dataclass, field
from typing import List, Tuple

from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes

from keyadmin.core.constants import SDL_KEYS_DIRNAME, TLOG_KEY_FILENAME

USERDATA_SIZE = 1024
BLANK_BYTE = 0xFF
LOG_KEY_SIZE = 16

LOG_ENTRY_SIZE = 16  # one AES block
LOG_CAPACITY = USERDATA_SIZE // LOG_ENTRY_SIZE  # 64

# Normal event block (see tamper_log_entry_t): uptime is 24-bit little-endian (3 bytes), then centiseconds.
LOG_ENTRY_FORMAT = "<BBBBIBBBBhH"
# Usage-dump block (see tamper_usage_entry_t): magic, type, 6 x uint16 counters, CRC-16.
USAGE_ENTRY_FORMAT = "<BBHHHHHHH"

LOG_ENTRY_MAGIC = 0xE7
LOG_FLAG_WIPE = 0x01
LOG_FLAG_COALESCED = 0x02
TYPE_SE_TAMPER_RESET = 0xF0
TYPE_USAGE_DUMP = 0xF1

# Same order as tamper_type_t / TAMPER_STR_* in KeyFirmware
TAMPER_TYPE_NAMES = (
    "Physical PIN1 (PC5-D5)", "Physical PIN2 (PC0-D0)", "VRX Payload Short", "VRX Token Invalid",
    "VRX Token Mismatch", "VRX No Session", "Extreme Temperature", "Voltage Glitch",
    "Digital/Clock Glitch", "EMP Injection",
)
# 3-letter codes for the compact column, same order as the names above.
TAMPER_TYPE_SHORT = (
    "PN1", "PN2", "VXS", "VXI", "VXM", "VXN", "TMP", "VLT", "DIG", "EMP",
)
PSEUDO_TYPE_NAMES = {TYPE_SE_TAMPER_RESET: "SE tamper reset (boot)", TYPE_USAGE_DUMP: "Usage counters snapshot"}
PSEUDO_TYPE_SHORT = {TYPE_SE_TAMPER_RESET: "RST", TYPE_USAGE_DUMP: "USE"}

# Usage counter labels for the dump, in firmware order starting at USAGE_COMPASS_SIM_PK
# (USAGE_TEST_ADD at index 0 is a test command and is excluded from the dump).
USAGE_NAMES = ("sim_pk", "sim_pk_gi", "safe", "ssp_a", "ssp_b", "ssp_c")


def type_name(code: int) -> str:
    if code < len(TAMPER_TYPE_NAMES):
        return TAMPER_TYPE_NAMES[code]
    return PSEUDO_TYPE_NAMES.get(code, f"Unknown type 0x{code:02X}")


def type_short(code: int) -> str:
    if code < len(TAMPER_TYPE_SHORT):
        return TAMPER_TYPE_SHORT[code]
    return PSEUDO_TYPE_SHORT.get(code, f"0x{code:02X}")


def default_key_path() -> str:
    admin_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    return os.path.join(admin_dir, SDL_KEYS_DIRNAME, TLOG_KEY_FILENAME)


def load_key(path: str = "") -> bytes:
    path = path or default_key_path()
    if not os.path.isfile(path):
        raise FileNotFoundError(f"Tamper Log Key not found: {path}. Run generate_tamper_log_key.py first.")
    with open(path, "rb") as f:
        key = f.read()
    if len(key) != LOG_KEY_SIZE:
        raise ValueError(f"Tamper Log Key {path} is {len(key)} bytes, expected {LOG_KEY_SIZE}")
    return key


@dataclass
class LogEntry:
    slot: int
    type_code: int
    valid: bool  # False: wrong key, or a write cut by power loss (magic/CRC mismatch after decryption)
    is_usage: bool = False
    count: int = 0
    wipe: bool = False
    coalesced: bool = False
    timestamp: int = 0
    centiseconds: int = 0
    uptime_seconds: int = 0
    temperature_c: float = 0.0
    usage: Tuple[int, ...] = ()


@dataclass
class TamperRecord:
    entries: List[LogEntry] = field(default_factory=list)

    @property
    def is_empty(self) -> bool:
        return not self.entries

    @property
    def wipe_triggered(self) -> bool:
        return any(e.valid and e.wipe for e in self.entries)


def _format_timestamp(timestamp: int, centiseconds: int) -> str:
    # The dongle RTC holds the UNIX time written by the provisioning PC; render it in local time for the
    # tester's convenience, as YYMMDD HHMMSS.cc (the "20" of the year is dropped on purpose).
    if timestamp == 0:
        return "RTC-not-set    "
    stamp = datetime.datetime.fromtimestamp(timestamp).strftime("%y%m%d %H%M%S")
    return f"{stamp}.{centiseconds:02d}"


def parse(data: bytes, key: bytes) -> TamperRecord:
    if len(data) < USERDATA_SIZE:
        raise ValueError(f"User Data dump is {len(data)} bytes, expected {USERDATA_SIZE}")
    decryptor = Cipher(algorithms.AES(key), modes.ECB()).decryptor()

    entries = []
    for slot in range(LOG_CAPACITY):
        offset = slot * LOG_ENTRY_SIZE
        raw = data[offset:offset + LOG_ENTRY_SIZE]
        if all(b == BLANK_BYTE for b in raw):
            continue
        plain = decryptor.update(raw)
        magic = plain[0]
        type_code = plain[1]
        crc = struct.unpack("<H", plain[14:16])[0]
        valid = magic == LOG_ENTRY_MAGIC and binascii.crc_hqx(plain[:14], 0xFFFF) == crc

        if type_code == TYPE_USAGE_DUMP:
            fields = struct.unpack(USAGE_ENTRY_FORMAT, plain)
            entries.append(LogEntry(slot=slot, type_code=type_code, valid=valid, is_usage=True,
                                    usage=fields[2:2 + len(USAGE_NAMES)]))
            continue

        _, _, count, flags, timestamp, up0, up1, up2, centi, temp_x10, _ = struct.unpack(LOG_ENTRY_FORMAT, plain)
        entries.append(LogEntry(slot=slot, type_code=type_code, valid=valid, count=count,
                                wipe=bool(flags & LOG_FLAG_WIPE), coalesced=bool(flags & LOG_FLAG_COALESCED),
                                timestamp=timestamp, centiseconds=centi,
                                uptime_seconds=up0 | (up1 << 8) | (up2 << 16),
                                temperature_c=temp_x10 / 10.0))
    return TamperRecord(entries=entries)


def format_report(record: TamperRecord) -> str:
    lines = [f"Tamper log: {len(record.entries)}/{LOG_CAPACITY} slots used"
             + (" | WIPE TRIGGERED" if record.wipe_triggered else "")]
    for e in record.entries:
        if not e.valid:
            lines.append(f"  #{e.slot:02d} [CORRUPT or wrong key]")
            continue
        if e.is_usage:
            counts = " ".join(f"{name}={val}" for name, val in zip(USAGE_NAMES, e.usage))
            lines.append(f"  #{e.slot:02d} {'':<15} USE  usage counters: {counts}")
            continue
        markers = ("  -> WIPE" if e.wipe else "") + ("  [coalesced]" if e.coalesced else "")
        lines.append(f"  #{e.slot:02d} {_format_timestamp(e.timestamp, e.centiseconds)} "
                     f"{type_short(e.type_code)} (#{e.count}) | {e.temperature_c:6.1f} C | "
                     f"{type_name(e.type_code)}{markers}")
    return "\n".join(lines)


def read_user_data_over_swd(outfile: str, pack_path: str, target: str, timeout_sec: int) -> bytes:
    """Dumps the User Data page with pyOCD in attach mode (no reset, so a temporarily opened port stays open)."""
    if os.path.exists(outfile):
        os.remove(outfile)
    savemem = f"savemem 0x0FE00000 {USERDATA_SIZE} {outfile}"
    cmd = [sys.executable, "-m", "pyocd", "cmd", "-t", target, "--pack", pack_path, "-M", "attach", "-c", savemem]
    result = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout_sec)
    if not os.path.isfile(outfile) or os.path.getsize(outfile) != USERDATA_SIZE:
        error = (result.stderr.strip() or result.stdout.strip() or str(result.returncode)).splitlines()[-1]
        raise RuntimeError(f"User Data read failed: {error}")
    with open(outfile, "rb") as f:
        return f.read()
