"""
Decoder for the tamper event log kept in the dongle's User Data page (0x0FE00000, 1 KB).

The layout mirrors KeyFirmware/src/core/tamper_manager.h (the firmware has a _Static_assert on the entry size):
    64 slots x 16 B, one entry per tamper event, newest kept when full. A blank slot is all 0xFF.
    Each entry is one AES-128-ECB block encrypted with the Tamper Log Key (keyadmin/keys/tamper_log_key.bin,
    generated by generate_tamper_log_key.py). Inside: magic, type, count, flags, RTC, uptime, temperature, CRC-16.
The page is not touched by a device erase, a mass erase or flashing, so it is readable after the live wipe.
"""
import binascii
import os
import struct
import subprocess
import sys
from dataclasses import dataclass, field
from typing import List

from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes

from keyadmin.core.constants import SDL_KEYS_DIRNAME, TLOG_KEY_FILENAME

USERDATA_SIZE = 1024
BLANK_BYTE = 0xFF
LOG_KEY_SIZE = 16

LOG_ENTRY_FORMAT = "<BBBBIIhH"
LOG_ENTRY_SIZE = struct.calcsize(LOG_ENTRY_FORMAT)  # 16 = one AES block
LOG_ENTRY_MAGIC = 0xE7
LOG_FLAG_WIPE = 0x01
LOG_CAPACITY = USERDATA_SIZE // LOG_ENTRY_SIZE  # 64

# Same order as tamper_type_t / TAMPER_STR_* in KeyFirmware
TAMPER_TYPE_NAMES = (
    "Physical PIN1 (PC5)", "Physical PIN2 (PC6)", "VRX Payload Short", "VRX Token Invalid",
    "VRX Token Mismatch", "VRX No Session", "Extreme Temperature", "Voltage Glitch",
    "Digital/Clock Glitch", "EMP Injection",
)
PSEUDO_TYPE_NAMES = {0xF0: "SE tamper reset (boot)"}


def type_name(code: int) -> str:
    if code < len(TAMPER_TYPE_NAMES):
        return TAMPER_TYPE_NAMES[code]
    return PSEUDO_TYPE_NAMES.get(code, f"Unknown type 0x{code:02X}")


def default_key_path() -> str:
    admin_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    return os.path.join(admin_dir, SDL_KEYS_DIRNAME, TLOG_KEY_FILENAME)


def load_key(path: str = "") -> bytes:
    path = path or default_key_path()
    if not os.path.isfile(path):
        raise FileNotFoundError(f"Tamper Log Key not found: {path}. Run generate_tamper_log_key.py first.")
    with open(path, "rb") as f:
        key = f.read()
    if len(key) != LOG_KEY_SIZE:
        raise ValueError(f"Tamper Log Key {path} is {len(key)} bytes, expected {LOG_KEY_SIZE}")
    return key


@dataclass
class LogEntry:
    slot: int
    type_code: int
    count: int
    wipe: bool
    timestamp: int
    uptime_seconds: int
    temperature_c: float
    valid: bool  # False: wrong key, or a write cut by power loss (magic/CRC mismatch after decryption)


@dataclass
class TamperRecord:
    entries: List[LogEntry] = field(default_factory=list)

    @property
    def is_empty(self) -> bool:
        return not self.entries

    @property
    def wipe_triggered(self) -> bool:
        return any(e.valid and e.wipe for e in self.entries)


def parse(data: bytes, key: bytes) -> TamperRecord:
    if len(data) < USERDATA_SIZE:
        raise ValueError(f"User Data dump is {len(data)} bytes, expected {USERDATA_SIZE}")
    decryptor = Cipher(algorithms.AES(key), modes.ECB()).decryptor()

    entries = []
    for slot in range(LOG_CAPACITY):
        offset = slot * LOG_ENTRY_SIZE
        raw = data[offset:offset + LOG_ENTRY_SIZE]
        if all(b == BLANK_BYTE for b in raw):
            continue
        plain = decryptor.update(raw)
        magic, type_code, count, flags, timestamp, uptime, temp_x10, crc = struct.unpack(LOG_ENTRY_FORMAT, plain)
        valid = magic == LOG_ENTRY_MAGIC and binascii.crc_hqx(plain[:-2], 0xFFFF) == crc
        entries.append(LogEntry(slot=slot, type_code=type_code, count=count, wipe=bool(flags & LOG_FLAG_WIPE),
                                timestamp=timestamp, uptime_seconds=uptime, temperature_c=temp_x10 / 10.0,
                                valid=valid))
    return TamperRecord(entries=entries)


def format_report(record: TamperRecord) -> str:
    lines = [f"Tamper log: {len(record.entries)}/{LOG_CAPACITY} slots used"
             + (" | WIPE TRIGGERED" if record.wipe_triggered else "")]
    for e in record.entries:
        if not e.valid:
            lines.append(f"  #{e.slot:02d} [CORRUPT or wrong key]")
            continue
        wipe = "  -> WIPE" if e.wipe else ""
        lines.append(f"  #{e.slot:02d} RTC {e.timestamp:>10} | uptime {e.uptime_seconds:>7}s | "
                     f"{e.temperature_c:6.1f} C | {type_name(e.type_code)} (#{e.count}){wipe}")
    return "\n".join(lines)


def read_user_data_over_swd(outfile: str, pack_path: str, target: str, timeout_sec: int) -> bytes:
    """Dumps the User Data page with pyOCD in attach mode (no reset, so a temporarily opened port stays open)."""
    if os.path.exists(outfile):
        os.remove(outfile)
    savemem = f"savemem 0x0FE00000 {USERDATA_SIZE} {outfile}"
    cmd = [sys.executable, "-m", "pyocd", "cmd", "-t", target, "--pack", pack_path, "-M", "attach", "-c", savemem]
    result = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout_sec)
    if not os.path.isfile(outfile) or os.path.getsize(outfile) != USERDATA_SIZE:
        error = (result.stderr.strip() or result.stdout.strip() or str(result.returncode)).splitlines()[-1]
        raise RuntimeError(f"User Data read failed: {error}")
    with open(outfile, "rb") as f:
        return f.read()
